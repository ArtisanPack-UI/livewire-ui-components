namespace ArtisanPack\LivewireUiComponents\Console\Commands;

use ArtisanPack\LivewireUiComponents\LivewireUiComponentsServiceProvider;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\File;

/**
 * Generates a Blade file that lists every registered component tag, under
 * the configured prefix, for IDE autocompletion.
 *
 * @since 1.0.0
 */
class GenerateIdeHelperCommand extends Command
{
    /**
     * The name and signature of the console command.
     *
     * @var string
     */
    protected $signature = 'artisanpack:generate-ide-helper';

    /**
     * The console command description.
     *
     * @var string
     */
    protected $description = 'Generate IDE helper file for ArtisanPack UI component autocompletion.';

    /**
     * Execute the console command.
     *
     * @since 1.0.0
     */
    public function handle(): int
    {
        $provider = $this->laravel->getProvider(LivewireUiComponentsServiceProvider::class)
            ?? new LivewireUiComponentsServiceProvider($this->laravel);

        $this->info(__('Generating IDE helper file for ArtisanPack UI components...'));

        $prefix   = LivewireUiComponentsServiceProvider::componentPrefix();
        $filePath = base_path('_ide_helper_artisanpack.blade.php');

        $content = "<?php\n/**\n * This file is generated automatically by the `artisanpack:generate-ide-helper` command.\n * Do not edit this file manually. It should be added to your .gitignore.\n */\n\n// @formatter:off\n?>\n\n";

        foreach (array_keys($provider->bladeComponents()) as $alias) {
            $name = LivewireUiComponentsServiceProvider::componentName($alias, $prefix);
            $content .= "<x-{$name} />\n";
        }

        $content .= "\n";

        foreach (array_keys($provider->livewireComponents()) as $alias) {
            $name = LivewireUiComponentsServiceProvider::componentName($alias, $prefix);
            $content .= "<livewire:{$name} />\n";
        }

        File::put($filePath, $content);

        $this->info(__('Helper file generated successfully at: :path', ['path' => $filePath]));

        return self::SUCCESS;
    }
}
