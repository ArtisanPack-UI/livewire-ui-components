<?php

declare(strict_types=1);

use Illuminate\Support\Facades\File;

beforeEach(function (): void {
    $this->presetDir = storage_path('test-presets');
    File::deleteDirectory($this->presetDir);
});

afterEach(function (): void {
    File::deleteDirectory($this->presetDir);
});

test('writes a CSS preset', function (): void {
    $path = $this->presetDir.'/acme.css';

    $this->artisan('artisanpack:generate-preset', ['name' => 'acme', '--primary' => '#7c3aed', '--output' => $path])
        ->expectsOutputToContain('primary: steel ramp')
        ->expectsOutputToContain('Preset "acme" written to')
        ->assertSuccessful();

    expect(File::get($path))
        ->toContain('@layer apui.tokens {')
        ->toContain('[data-preset="acme"] {')
        ->toContain('Generated by php artisan artisanpack:generate-preset');
});

test('writes to resources/css/presets by default', function (): void {
    $path = resource_path('css/presets/default-path.css');
    File::delete($path);

    $this->artisan('artisanpack:generate-preset', ['name' => 'default-path', '--primary' => '#1f6f3d'])
        ->assertSuccessful();

    expect(File::exists($path))->toBeTrue();
    File::delete($path);
});

test('writes PHP and JSON data', function (string $format): void {
    $path = $this->presetDir."/acme.{$format}";

    $this->artisan('artisanpack:generate-preset', [
        'name'      => 'acme',
        '--primary' => '#7c3aed',
        '--accent'  => '#f59e0b',
        '--format'  => $format,
        '--output'  => $path,
    ])->assertSuccessful();

    $data = 'php' === $format ? require $path : json_decode(File::get($path), true);
    expect($data['name'])->toBe('acme')
        ->and($data['attribute'])->toBe('data-preset')
        ->and($data['tokens']['steel.600']['changed'])->toBeTrue()
        ->and($data['tokens']['marigold.300']['changed'])->toBeTrue();
})->with(['php', 'json']);

test('passes the font and neutral options through', function (): void {
    $path = $this->presetDir.'/acme.css';

    $this->artisan('artisanpack:generate-preset', [
        'name'        => 'acme',
        '--primary'   => '#7c3aed',
        '--neutral'   => 'keep',
        '--font-sans' => 'Inter, system-ui, sans-serif',
        '--output'    => $path,
    ])->assertSuccessful();

    expect(File::get($path))
        ->toContain('--apui-font-family-sans: Inter, system-ui, sans-serif;')
        ->not->toContain('--apui-gray-500:');
});

test('fails without writing on invalid input', function (array $arguments, string $message): void {
    $path = $this->presetDir.'/bad.css';

    $this->artisan('artisanpack:generate-preset', [...$arguments, '--output' => $path, '--no-interaction' => true])
        ->expectsOutputToContain($message)
        ->assertFailed();

    expect(File::exists($path))->toBeFalse();
})->with([
    'bad color'   => [['name' => 'bad', '--primary' => 'green'], 'is not a hex color'],
    'bad name'    => [['name' => 'Bad Name', '--primary' => '#7c3aed'], 'is not a valid preset name'],
    'bad neutral' => [['name' => 'bad', '--primary' => '#7c3aed', '--neutral' => 'warm'], 'neutral must be tinted, pure or keep'],
    'bad format'  => [['name' => 'bad', '--primary' => '#7c3aed', '--format' => 'scss'], '--format must be one of'],
    'no primary'  => [['name' => 'bad'], 'a primary color is required'],
]);

test('asks for the name and primary color when they are missing', function (): void {
    $path = $this->presetDir.'/asked.css';

    $this->artisan('artisanpack:generate-preset', ['--output' => $path])
        ->expectsQuestion('Preset name', 'asked')
        ->expectsQuestion('Primary brand color', '#0055ff')
        ->assertSuccessful();

    expect(File::get($path))->toContain('[data-preset="asked"]');
});

test('does not overwrite an existing file without --force', function (): void {
    $path = $this->presetDir.'/acme.css';
    File::ensureDirectoryExists($this->presetDir);
    File::put($path, 'keep me');

    $this->artisan('artisanpack:generate-preset', ['name' => 'acme', '--primary' => '#7c3aed', '--output' => $path, '--no-interaction' => true])
        ->expectsOutputToContain('Use --force to overwrite it')
        ->assertFailed();
    expect(File::get($path))->toBe('keep me');

    $this->artisan('artisanpack:generate-preset', ['name' => 'acme', '--primary' => '#7c3aed', '--output' => $path, '--force' => true])
        ->assertSuccessful();
    expect(File::get($path))->toContain('[data-preset="acme"]');
});

test('warns that artisanpack:generate-theme is deprecated', function (): void {
    config()->set('artisanpack.livewire-ui-components.theme_output_path', storage_path('test-theme.css'));

    $this->artisan('artisanpack:generate-theme')
        ->expectsOutputToContain('artisanpack:generate-theme is deprecated')
        ->assertSuccessful();

    File::delete(storage_path('test-theme.css'));
});
