<?php

declare(strict_types=1);

use ArtisanPack\LivewireUiComponents\Exceptions\ThemeGeneratorException;
use ArtisanPack\LivewireUiComponents\Theming\ColorMath;
use ArtisanPack\LivewireUiComponents\Theming\DesignTokens;
use ArtisanPack\LivewireUiComponents\Theming\PresetGenerator;

/**
 * The golden fixtures come from the design system's generator
 * (packages/tokens/test/fixtures/generator). Same inputs, same output.
 */
function generatorFixtures(): array
{
    $fixtures = [];
    foreach (glob(dirname(__DIR__, 2).'/Fixtures/design-system/generator/*.json') as $file) {
        $fixtures[basename($file, '.json')] = [json_decode((string) file_get_contents($file), true)];
    }

    return $fixtures;
}

dataset('generator fixtures', generatorFixtures());

const JS_SOURCE = 'Generated by apui-generate-preset. Regenerate rather than edit by hand.';

test('matches the design system generator', function (array $fixture): void {
    $preset = PresetGenerator::make()->generate([
        ...$fixture['options'],
        'description' => $fixture['data']['description'],
    ]);

    expect($preset->passes())->toBeTrue()
        ->and($preset->anchors)->toBe($fixture['anchors'])
        ->and($preset->css(JS_SOURCE))->toBe($fixture['css'])
        ->and(json_decode((string) json_encode($preset->toArray()), true))->toBe($fixture['data']);
})->with('generator fixtures');

test('places the input exactly on the step nearest its luminance', function (): void {
    $preset = PresetGenerator::make()->generate(['name' => 'brand', 'primary' => '#1f6f3d']);

    expect($preset->anchors['primary'])->toBe(['ramp' => 'steel', 'step' => '700', 'exact' => true])
        ->and($preset->resolved('color.primary-hover'))->toBe('#1f6f3d');
});

test('keeps the default ramp luminance per step', function (): void {
    $tokens = DesignTokens::load();
    $ramp   = (new PresetGenerator($tokens))->generateRamp('steel', ColorMath::parseHex('#c2185b'));

    foreach ($ramp['steps'] as $step => $rgb) {
        $target = ColorMath::luminance(ColorMath::parseHex($tokens->get("steel.{$step}")['resolved']));
        expect(abs(ColorMath::luminance($rgb) - $target))->toBeLessThan(0.004);
    }
});

test('passes every contrast pair for a wide range of colors', function (string $primary): void {
    expect(PresetGenerator::make()->generate(['name' => 'brand', 'primary' => $primary])->failures)->toBe([]);
})->with(['#ff0000', '#ffee00', '#00e5ff', '#7c3aed', '#111111', '#fafafa', '#808080']);

test('finds the ramp under each color role', function (): void {
    $generator = PresetGenerator::make();

    expect($generator->rampFor('primary'))->toBe('steel')
        ->and($generator->rampFor('secondary'))->toBe('slate')
        ->and($generator->rampFor('accent'))->toBe('marigold');
});

test('writes pure grays with neutral pure', function (): void {
    $preset = PresetGenerator::make()->generate(['name' => 'brand', 'primary' => '#1f6f3d', 'neutral' => 'pure']);
    $gray   = $preset->resolved('gray.600');

    expect(substr($gray, 1, 2))->toBe(substr($gray, 3, 2))
        ->and(substr($gray, 3, 2))->toBe(substr($gray, 5, 2))
        ->and($preset->resolved('state.hover'))->toContain(' 0 0 /');
});

test('leaves the grays alone with neutral keep', function (): void {
    $preset = PresetGenerator::make()->build(['name' => 'brand', 'primary' => '#1f6f3d', 'neutral' => 'keep']);

    expect(array_filter(array_keys($preset->overrides), fn (string $path): bool => str_starts_with($path, 'gray.')))->toBe([]);
});

test('declares every dependent of a reassigned token', function (): void {
    $preset = PresetGenerator::make()->generate(['name' => 'brand', 'primary' => '#7c3aed']);
    $css    = $preset->css();

    expect($css)->toContain('@layer apui.tokens {')
        ->and($css)->toContain('[data-preset="brand"] {')
        ->and($css)->toContain('[data-theme="dark"] [data-preset="brand"]')
        ->and($css)->toContain('--apui-color-primary: var(--apui-steel-600);')
        ->and($css)->toContain('--apui-selected-bg: var(--apui-color-primary-soft);')
        ->and($css)->toContain('Generated by php artisan artisanpack:generate-preset');
});

test('rejects invalid input', function (array $options, string $message): void {
    expect(fn () => PresetGenerator::make()->generate($options))
        ->toThrow(ThemeGeneratorException::class, $message);
})->with([
    'bad name'       => [['name' => 'Brand', 'primary' => '#1f6f3d'], 'not a valid preset name'],
    'no primary'     => [['name' => 'brand'], 'a primary color is required'],
    'bad neutral'    => [['name' => 'brand', 'primary' => '#1f6f3d', 'neutral' => 'warm'], 'neutral must be tinted, pure or keep'],
    'bad color'      => [['name' => 'brand', 'primary' => 'green'], 'is not a hex color'],
    'empty families' => [['name' => 'brand', 'primary' => '#1f6f3d', 'fontSans' => ' , '], 'must not be empty'],
    'escaping font'  => [['name' => 'brand', 'primary' => '#1f6f3d', 'fontSans' => 'Evil\\'], 'must not contain'],
    'breaking font'  => [['name' => 'brand', 'primary' => '#1f6f3d', 'fontSans' => 'a; } body { color: red'], 'must not contain'],
]);

test('keeps a description from ending the CSS comment', function (): void {
    $css = PresetGenerator::make()->generate([
        'name'        => 'brand',
        'primary'     => '#1f6f3d',
        'description' => "evil */ body { display: none } /*\nsecond line",
    ])->css();

    expect($css)->toContain(' * evil * / body { display: none } /* second line')
        ->and(substr_count($css, '*/'))->toBe(1);
});
